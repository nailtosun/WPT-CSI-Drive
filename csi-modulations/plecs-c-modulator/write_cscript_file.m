%% write_cscript_file.m
% Writes the C code of csiModulatorCode.m to csi_modulator_cscript.c, with
% each part marked by the PLECS C-Script section it belongs to. The .c file
% is for reading and for porting to a microcontroller; PLECS needs the parts
% pasted into the corresponding sections of a C-Script block.

here = fileparts(mfilename('fullpath'));
[decl, start, outp] = csiModulatorCode();
fid = fopen(fullfile(here, 'csi_modulator_cscript.c'), 'w');
fprintf(fid, '/* Two-level CSI modulator, PLECS C-Script. Generated by write_cscript_file.m from\n');
fprintf(fid, '   csiModulatorCode.m; do not edit here. Interface and methods: see csiModulatorCode.m. */\n\n');
fprintf(fid, '/* ===== Code declarations ===== */\n%s\n\n', strjoin(decl, newline));
fprintf(fid, '/* ===== Start function code ===== */\n%s\n\n', strjoin(start, newline));
fprintf(fid, '/* ===== Output function code ===== */\n%s\n', strjoin(outp, newline));
fclose(fid);
fprintf('written %s\n', fullfile(here, 'csi_modulator_cscript.c'));
